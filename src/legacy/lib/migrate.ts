/**
 * migrate.ts — Deterministic migration from legacy tracker shapes to v9-canonical.
 *
 * Detects the tracker version and computes the set of changes needed.
 * In dry-run mode: prints a diff to stdout with no filesystem writes.
 * In apply mode: writes all changes atomically and records a migration log.
 *
 * Exported for testability:
 *   detectVersion       — classify current tracker shape
 *   planMigration       — compute list of changes (no I/O writes)
 *   applyMigration      — execute changes + write log
 *   formatDiff          — render unified-diff-style output
 *
 * The loose-mode parser (parseFrontmatterLoose) is used ONLY inside this module.
 * All other CLI paths continue to use the strict schemas.
 */

import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  mkdirSync,
  unlinkSync,
} from "node:fs";
import { join, basename, relative, dirname } from "node:path";
import { parseFrontmatter, serializeFrontmatter } from "./markdown/frontmatter.ts";
import { atomicWriteFileSync } from "./atomic.ts";
import { readTrackerState } from "./tracker-reader.ts";
import { rebuildIndexDoc } from "./index-rebuilder.ts";
import { CURRENT_SCHEMA_VERSION } from "./version.ts";
import { isWorklogIndexFile } from "./worklog.ts";

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

const GENERATED_HEADER =
  "<!-- Generated by darius. Do not edit; run `darius index --rebuild`. -->";
/** The header before 0.77.0: an index that has it is current too. */
const PREVIOUS_GENERATED_HEADER =
  "<!-- Generated by tracker CLI. Do not edit; run `tracker index --rebuild`. -->";

// ---------------------------------------------------------------------------
// Version detection
// ---------------------------------------------------------------------------

export type TrackerVersion = "v1" | "v8" | "v9";

/**
 * Detect the current tracker shape by examining the .tracker/ directory.
 *
 * v1: .tracker/ contains *.md spec files at root (no milestone M{N}-* folders)
 * v8: milestone folders exist but specs have status:/verified: in frontmatter,
 *     OR 00-INDEX.md lacks the generator header,
 *     OR worklog entries use mixed-prefix conventions
 * v9: clean canonical state (nothing to migrate)
 */
export function detectVersion(trackerRoot: string): TrackerVersion {
  const entries = readdirSync(trackerRoot);

  // Look for milestone folders (M{N}-* pattern)
  const milestoneFolders = entries.filter((e) => {
    const full = join(trackerRoot, e);
    return statSync(full).isDirectory() && /^M\d+-.+$/.test(e);
  });

  // v1: spec files (.md) at root level that are NOT 00-INDEX.md
  const rootSpecFiles = entries.filter((e) => {
    if (!e.endsWith(".md")) return false;
    if (e === "00-INDEX.md") return false;
    const full = join(trackerRoot, e);
    return statSync(full).isFile();
  });

  if (milestoneFolders.length === 0 && rootSpecFiles.length > 0) {
    return "v1";
  }

  // Check for v8 drift signals
  if (milestoneFolders.length > 0) {
    // Check 1: 00-INDEX.md missing generator header
    const indexPath = join(trackerRoot, "00-INDEX.md");
    if (existsSync(indexPath)) {
      const indexContent = readFileSync(indexPath, "utf-8");
      if (!indexContent.includes(GENERATED_HEADER) && !indexContent.includes(PREVIOUS_GENERATED_HEADER)) {
        return "v8";
      }
    }

    // Check 2: Any spec has status: or verified: in frontmatter
    for (const folder of milestoneFolders) {
      const fullFolder = join(trackerRoot, folder);
      const specFiles = getSpecFilesInFolder(fullFolder);
      for (const specPath of specFiles) {
        const raw = readFileSync(specPath, "utf-8");
        const { data } = parseFrontmatterLoose(raw);
        if ("status" in data || "verified" in data) {
          return "v8";
        }
      }
    }
  }

  return "v9";
}

// ---------------------------------------------------------------------------
// Migration planning
// ---------------------------------------------------------------------------

export type MigrationChangeAction = "created" | "modified" | "moved";

export type MigrationChange = {
  step: string;
  file: string; // relative path from trackerRoot parent
  action: MigrationChangeAction;
  reason: string;
  /** New content (undefined for moves where content unchanged) */
  newContent?: string;
  /** For moves: the destination path (absolute) */
  destPath?: string;
};

export type MigrationPlan = {
  version: TrackerVersion;
  changes: MigrationChange[];
};

/**
 * Compute all changes required to bring the tracker to v9-canonical state.
 * Does NOT perform any writes — pure computation.
 */
export function planMigration(opts: {
  trackerRoot: string;
  fromVersion?: TrackerVersion;
}): MigrationPlan {
  const { trackerRoot } = opts;
  const version = opts.fromVersion ?? detectVersion(trackerRoot);

  if (version === "v9") {
    return { version, changes: [] };
  }

  const changes: MigrationChange[] = [];
  const repoRoot = dirname(trackerRoot);

  if (version === "v1") {
    // migrateV1ToV2: move flat *.md files into M1-<name>/ folder
    const rootSpecFiles = readdirSync(trackerRoot).filter((e) => {
      if (!e.endsWith(".md")) return false;
      if (e === "00-INDEX.md") return false;
      const full = join(trackerRoot, e);
      return statSync(full).isFile();
    });

    if (rootSpecFiles.length > 0) {
      const slug = "migrated";
      const folderName = "M1-migrated";
      const folderPath = join(trackerRoot, folderName);

      // Scaffold a minimal README for the synthetic milestone
      const readmeContent = buildMilestoneReadme({
        name: "Migrated Specs",
        slug,
        date: todayIsoString(),
        target: "TBD",
        owner: "unknown",
      });

      changes.push({
        step: "migrateV1ToV2",
        file: relative(repoRoot, join(folderPath, "00-README.md")),
        action: "created",
        reason: "scaffold milestone folder for flat v1 specs",
        newContent: readmeContent,
        destPath: join(folderPath, "00-README.md"),
      });

      for (const specFile of rootSpecFiles) {
        const srcPath = join(trackerRoot, specFile);
        const destPath = join(folderPath, specFile);
        const content = readFileSync(srcPath, "utf-8");
        changes.push({
          step: "migrateV1ToV2",
          file: relative(repoRoot, destPath),
          action: "moved",
          reason: `move flat v1 spec into milestone folder ${folderName}`,
          newContent: content,
          destPath,
        });
      }
    }

    // Also run v8 migration steps after v1->v2
    addV8Changes({ trackerRoot, changes, repoRoot, tempMilestoneFolders: ["M1-migrated"] });
  } else {
    // v8: run drift-correction steps only
    addV8Changes({ trackerRoot, changes, repoRoot, tempMilestoneFolders: [] });
  }

  // Always regenerate index as final step
  changes.push({
    step: "regenerateIndex",
    file: relative(repoRoot, join(trackerRoot, "00-INDEX.md")),
    action: "modified",
    reason: "regenerate 00-INDEX.md with canonical generator header",
    destPath: join(trackerRoot, "00-INDEX.md"),
    // newContent is computed at apply time from TrackerState
  });

  return { version, changes };
}

// ---------------------------------------------------------------------------
// Migration application
// ---------------------------------------------------------------------------

export type ApplyResult = {
  appliedCount: number;
  logPath: string | null; // null in dry-run
  changes: MigrationChange[];
};

/**
 * Apply all migration changes to the filesystem (or describe them in dry-run).
 *
 * In apply mode:
 *   - All writes go through atomicWriteFileSync
 *   - A migration log is written to .tracker/.migration-<ISO-date>.log
 *
 * In dry-run mode:
 *   - No filesystem writes
 *   - Returns changes for diff formatting
 */
export function applyMigration(opts: {
  trackerRoot: string;
  plan: MigrationPlan;
  dryRun: boolean;
}): ApplyResult {
  const { trackerRoot, plan, dryRun } = opts;
  const { changes } = plan;

  if (changes.length === 0) {
    return { appliedCount: 0, logPath: null, changes: [] };
  }

  if (dryRun) {
    return { appliedCount: changes.length, logPath: null, changes };
  }

  // --- Apply mode ---
  const timestamp = new Date().toISOString();
  const logLines: string[] = [];

  // Separate index regeneration from other changes
  const indexChange = changes.find((c) => c.step === "regenerateIndex");
  const otherChanges = changes.filter((c) => c.step !== "regenerateIndex");

  for (const change of otherChanges) {
    if (!change.destPath) continue;

    // Ensure parent directory exists
    const parentDir = dirname(change.destPath);
    if (!existsSync(parentDir)) {
      mkdirSync(parentDir, { recursive: true });
    }

    const content = change.newContent ?? "";
    atomicWriteFileSync(change.destPath, content);

    // For "moved" actions, remove the source file
    // Source is the file at trackerRoot/<basename(destPath)>
    if (change.action === "moved") {
      const srcPath = join(trackerRoot, basename(change.destPath));
      if (existsSync(srcPath) && srcPath !== change.destPath) {
        try {
          unlinkSync(srcPath);
        } catch {
          // Best effort
        }
      }
    }

    logLines.push(
      `[${timestamp}] STEP=${change.step} FILE=${change.file} ACTION=${change.action} REASON=${change.reason}`,
    );
  }

  // Regenerate the index last (needs actual TrackerState from disk)
  if (indexChange) {
    try {
      const state = readTrackerState(trackerRoot);
      const indexContent = rebuildIndexDoc(state);
      const indexPath = indexChange.destPath ?? join(trackerRoot, "00-INDEX.md");
      atomicWriteFileSync(indexPath, indexContent);
      logLines.push(
        `[${timestamp}] STEP=regenerateIndex FILE=${indexChange.file} ACTION=modified REASON=regenerate 00-INDEX.md with canonical generator header`,
      );
    } catch {
      // Index rebuild might fail on v1 before folders are set up; non-fatal
    }
  }

  // Write the migration log
  const logFileName = `.migration-${formatISOForFileName(new Date())}.log`;
  const logPath = join(trackerRoot, logFileName);
  atomicWriteFileSync(logPath, logLines.join("\n") + "\n");

  return { appliedCount: changes.length, logPath, changes };
}

