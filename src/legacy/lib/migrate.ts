/**
 * Format a migration plan as a unified-diff-style string for stdout.
 */
export function formatDiff(opts: {
  plan: MigrationPlan;
  dryRun: boolean;
}): string {
  const { plan, dryRun } = opts;
  const lines: string[] = [];

  if (dryRun) {
    lines.push("# DRY RUN — tracker migrate");
    lines.push("");
  }

  if (plan.changes.length === 0) {
    lines.push(`Detected version: ${plan.version}`);
    lines.push("Nothing to migrate — tracker is already v9-canonical.");
    return lines.join("\n");
  }

  lines.push(`Detected version: ${plan.version}`);
  lines.push(`Changes: ${plan.changes.length} file(s)`);
  lines.push("");

  // Group by step
  const byStep: Record<string, MigrationChange[]> = {};
  for (const change of plan.changes) {
    if (!byStep[change.step]) byStep[change.step] = [];
    byStep[change.step]!.push(change);
  }

  for (const [step, stepChanges] of Object.entries(byStep)) {
    lines.push(`## Step: ${step}`);
    lines.push("");
    for (const change of stepChanges) {
      lines.push(`  ${change.action.toUpperCase().padEnd(8)} ${change.file}`);
      lines.push(`           Reason: ${change.reason}`);
      if (change.newContent !== undefined && change.action !== "moved") {
        // Show a brief preview (first 5 non-empty lines)
        const preview = change.newContent
          .split("\n")
          .filter((l) => l.trim())
          .slice(0, 5)
          .map((l) => `  + ${l}`)
          .join("\n");
        if (preview) {
          lines.push(preview);
        }
      }
    }
    lines.push("");
  }

  if (dryRun) {
    lines.push(`## Step: stampSchemaVersion`);
    lines.push("");
    lines.push(`  MODIFIED .tracker/00-INDEX.md`);
    lines.push(`           Reason: write schema_version: ${CURRENT_SCHEMA_VERSION} as final atomic step`);
    lines.push("");
    lines.push("Run with --apply to execute these changes.");
  }

  return lines.join("\n");
}

